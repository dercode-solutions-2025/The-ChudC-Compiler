/*
This is a little C compiler that generates basic ARM64 instructions designed to be compiled by Clang.

Yeah that's basically it so here are the maps:

"return 10;" maps to:
mov w0, #10
ret

"int main() {<body>}" maps to:
main:
    stp     x29, x30, [sp, #-16]!
    mov     x29, sp
    
    <compiled body here>
    
    ldp     x29, x30, [sp], #16
    ret

*/

#ifndef CHUDC_HPP
#define CHUDC_HPP
#include <iostream>
#include <string>
#include <cstdlib>

void quit(std::string msg, int code) {
	std::cout << msg;
	std::cout << "\nQuitting with exit code " << code << ".\n";
	std::exit(code);
}

std::string compile(std::string script) {
	int ptr = 0;
	std::string out = "";
	out += "// Generated by the ChudC compiler\n";
	while (ptr <= script.size()) {
		if (script.substr(ptr, 3) == "int") {
			ptr += 3;
			if (script[ptr] == ' ') {
				ptr++;
				std::string temp = "";
				while (script[ptr] != '(' && ptr <= script.size()) {
					temp += script[ptr];
					ptr++;
				}
				out += ".global ";
				out += temp;
				out += '\n';
				out += temp;
				out += ":\n";
				out += "    stp x29, x30, [sp, #-16]!";
				out += "\n    mov x29, sp\n";
				ptr += 2;
				if (script[ptr] == ' ' || script[ptr] == '{') {
					ptr++;
					continue;
				} else {
					std::string err = "Error: Expecting ' ' or '{', but found '";
					err += script[ptr];
					err += "'. This violates C standards.";
					quit(err, 1);
				}
			} else {
				std::string err = "Error: Expecting ' ', found '";
				err += script[ptr];
				err += "'. This violates C standards.";
				quit(err, 1);
			}
		} else if (script.substr(ptr, 6) == "return") {
			ptr += 6;
			std::string temp = "";
			if (script[ptr] == ' ') {
				ptr++;
				while (script[ptr] != ';') {
					temp += script[ptr];
					ptr++;
				}
				out += "    mov w0, #";
				out += temp;
				out += "\n    ldp x29, x30, [sp], #16\n";
				out += "    ret\n\n";
				while (script[ptr] != '}') {
					ptr++;
				}
			} else {
				std::string err = "Error: Expecting ' ', found '";
				err += script[ptr];
				err += "'";
				quit(err, 1);
			}
		} else {
			ptr++;
		}
	}
	return out;
}
#endif